def build_frame() -> pd.DataFrame:
    rows = []
    for doc in DOCS:
        title = clean_text(doc["title"])
        body = clean_text(f"{title}\n\n{clean_text(doc['text'])}")
        for j, part in enumerate(split_doc(body, chunk_size=900, overlap=150)):
            rows.append(
                {
                    "web_id": doc["web_id"],
                    "title": title,
                    "url": doc["url"],
                    "chunk_no": j,
                    "text": part,
                }
            )
    return pd.DataFrame(rows)


def main() -> None:
    ap = argparse.ArgumentParser(description="Build a synthetic demo corpus parquet")
    ap.add_argument("--out", default="data/demo_chunks.parquet")
    args = ap.parse_args()

    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)

    df = build_frame()
    df.to_parquet(out, index=False)
    print(f"Saved: {out} | docs={df['web_id'].nunique()} chunks={len(df)}")


if __name__ == "__main__":
    main()
